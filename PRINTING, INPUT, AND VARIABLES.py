# PRINTING, INPUT, AND VARIABLES

# ========== EASY ==========

# Example 1: Simple Printing
print("Hello, World!")

# Example 2: Printing Your Name
print("My name is Alex")

# Example 3: Printing Multiple Lines
print("Hello!")
print("Welcome to Python!")
print("Let's learn coding.")


# ========== INTERMEDIATE ==========

# Example 4: Using Variables
name = "Alex"
age = 18
print("Name:", name)
print("Age:", age)

# Example 5: Getting User Input
name = input("Enter your name: ")
print("Hello,", name)

# Example 6: Input with Numbers
age = int(input("Enter your age: "))
print("You are", age, "years old.")


# ========== HARD ==========

# Example 7: Calculating Two Numbers
num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))
total = num1 + num2
print("The sum is:", total)

# Example 8: Personal Information
name = input("Enter your name: ")
age = int(input("Enter your age: "))
course = input("Enter your course: ")

print("--- STUDENT INFORMATION ---")
print("Name:", name)
print("Age:", age)
print("Course:", course)
